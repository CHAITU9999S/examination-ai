
import os
from datetime import datetime, timedelta, timezone
from typing import Optional

from jose import JWTError, jwt
from passlib.context import CryptContext


# ==========================================
# AUTHENTICATION CONFIGURATION
# ==========================================

JWT_SECRET_KEY = os.getenv(
    "JWT_SECRET_KEY",
    "development-only-secret-change-before-deployment"
)

JWT_ALGORITHM = os.getenv("JWT_ALGORITHM", "HS256")

ACCESS_TOKEN_EXPIRE_MINUTES = int(
    os.getenv("ACCESS_TOKEN_EXPIRE_MINUTES", "30")
)


# ==========================================
# PASSWORD HASHING
# ==========================================

password_context = CryptContext(
    schemes=["bcrypt"],
    deprecated="auto"
)


def hash_password(password: str) -> str:
    """Hash a password before storing it in the database."""

    return password_context.hash(password)


def verify_password(
    plain_password: str,
    hashed_password: str
) -> bool:
    """Verify a submitted password against its stored hash."""

    return password_context.verify(
        plain_password,
        hashed_password
    )


# ==========================================
# NORMAL JWT ACCESS TOKEN CREATION
# ==========================================

def create_access_token(
    subject: str | dict | None = None,
    expires_delta: Optional[timedelta] = None,
    *,
    data: Optional[dict] = None,
) -> str:
    """
    Create a signed JWT token for normal API authentication.

    Accepts either a subject string or a claims dictionary for
    backward compatibility. Expiry and token type are always
    generated by this function and cannot be overridden by callers.
    """

    if subject is not None and data is not None:
        raise ValueError("Provide either subject or data, not both.")

    token_data = data if data is not None else subject

    if isinstance(token_data, dict):
        payload = dict(token_data)
    elif isinstance(token_data, str) and token_data.strip():
        payload = {"sub": token_data.strip()}
    else:
        raise ValueError("A non-empty token subject is required.")

    token_subject = payload.get("sub")

    if token_subject is None or not str(token_subject).strip():
        raise ValueError("A non-empty token subject is required.")

    payload["sub"] = str(token_subject)

    now = datetime.now(timezone.utc)

    if expires_delta is None:
        expires_delta = timedelta(
            minutes=ACCESS_TOKEN_EXPIRE_MINUTES
        )

    if expires_delta.total_seconds() <= 0:
        raise ValueError("Token expiry must be in the future")

    payload["iat"] = now
    payload["exp"] = now + expires_delta
    payload["token_type"] = "access"

    return jwt.encode(
        payload,
        JWT_SECRET_KEY,
        algorithm=JWT_ALGORITHM
    )


# ==========================================
# EXAMINATION ACCESS TOKEN CREATION
# ==========================================

def create_exam_access_token(
    exam_id: int,
    student_id: int,
    session_id: int,
    expires_at: datetime
) -> str:
    """
    Create an examination-specific JWT token.

    The token is bound to one examination, one student,
    and one examination session.
    """

    if not all(
        isinstance(value, int) and not isinstance(value, bool) and value > 0
        for value in (exam_id, student_id, session_id)
    ):
        raise ValueError(
            "Exam, student and session IDs must be positive integers"
        )

    if not isinstance(expires_at, datetime):
        raise ValueError("A valid examination expiry time is required")

    if expires_at.tzinfo is None:
        expires_at_utc = expires_at.replace(tzinfo=timezone.utc)
    else:
        expires_at_utc = expires_at.astimezone(timezone.utc)

    now = datetime.now(timezone.utc)

    if expires_at_utc <= now:
        raise ValueError("Examination token expiry must be in the future")

    payload = {
        "sub": str(student_id),
        "exam_id": exam_id,
        "student_id": student_id,
        "session_id": session_id,
        "iat": now,
        "exp": expires_at_utc,
        "token_type": "exam",
    }

    return jwt.encode(
        payload,
        JWT_SECRET_KEY,
        algorithm=JWT_ALGORITHM
    )


# ==========================================
# JWT TOKEN VERIFICATION
# ==========================================

def verify_token(
    token: str,
    expected_token_type: Optional[str] = None
) -> Optional[dict]:
    """
    Decode and verify a JWT token.

    Returns the decoded payload when valid.
    Returns None when invalid, expired or of the wrong type.
    """

    try:
        payload = jwt.decode(
            token,
            JWT_SECRET_KEY,
            algorithms=[JWT_ALGORITHM]
        )

        if (
            expected_token_type is not None
            and payload.get("token_type") != expected_token_type
        ):
            return None

        return payload

    except (JWTError, TypeError, ValueError):
        return None
