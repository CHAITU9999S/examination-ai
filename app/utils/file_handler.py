
import io
import os
import uuid

from pathlib import Path

from PIL import (
    Image,
    ImageOps,
    UnidentifiedImageError,
)


# ==========================================
# CONFIGURATION
# ==========================================

MAX_FILE_SIZE_BYTES = 10 * 1024 * 1024  # 10 MB

MAX_IMAGE_PIXELS = 25_000_000

ALLOWED_IMAGE_FORMATS = {
    "JPEG",
    "PNG",
    "WEBP",
    "TIFF",
    "BMP",
}

THUMBNAIL_SIZE = (400, 400)

DEFAULT_UPLOAD_DIRECTORY = "uploads/answers"


# ==========================================
# UPLOAD DIRECTORY
# ==========================================

def get_upload_directory(
    upload_dir=None,
) -> Path:
    """
    Return the resolved upload directory.

    The default directory can be configured through UPLOAD_DIR.
    """

    if upload_dir is None:
        upload_dir = os.getenv(
            "UPLOAD_DIR",
            DEFAULT_UPLOAD_DIRECTORY,
        )

    directory = Path(upload_dir).expanduser().resolve()

    directory.mkdir(
        parents=True,
        exist_ok=True,
    )

    return directory


# ==========================================
# IMAGE VALIDATION
# ==========================================

def validate_uploaded_image(
    image_bytes: bytes,
):
    """
    Validate image content, format, size and dimensions.
    """

    if not isinstance(image_bytes, bytes) or not image_bytes:
        raise ValueError("An image file is required.")

    if len(image_bytes) > MAX_FILE_SIZE_BYTES:
        raise ValueError("Image size cannot exceed 10 MB.")

    try:
        with Image.open(io.BytesIO(image_bytes)) as image:
            if image.format not in ALLOWED_IMAGE_FORMATS:
                raise ValueError("Unsupported image format.")

            width, height = image.size

            if width <= 0 or height <= 0:
                raise ValueError("Invalid image dimensions.")

            if width * height > MAX_IMAGE_PIXELS:
                raise ValueError("Image dimensions are too large.")

            image.verify()

    except ValueError:
        raise

    except (
        UnidentifiedImageError,
        OSError,
        Image.DecompressionBombError,
    ) as exc:
        raise ValueError("Uploaded file is not a valid image.") from exc

    return True


# ==========================================
# SAFE IMAGE PROCESSING
# ==========================================

def _prepare_image(
    image_bytes: bytes,
):
    """
    Open and normalize an uploaded image.

    Images are converted to RGB JPEG to remove unnecessary
    metadata and provide a consistent stored format.
    """

    validate_uploaded_image(image_bytes)

    try:
        with Image.open(io.BytesIO(image_bytes)) as source:
            image = ImageOps.exif_transpose(source)

            image = image.convert("RGB")

            image.thumbnail(
                (3000, 3000),
                Image.Resampling.LANCZOS,
            )

            output = io.BytesIO()

            image.save(
                output,
                format="JPEG",
                quality=90,
                optimize=True,
            )

            return image.copy(), output.getvalue()

    except (
        UnidentifiedImageError,
        OSError,
        ValueError,
    ) as exc:
        raise ValueError("Unable to process uploaded image.") from exc


# ==========================================
# SAFE FILE PATH RESOLUTION
# ==========================================

def get_safe_upload_path(
    stored_filename: str,
    upload_dir=None,
) -> Path:
    """
    Resolve a stored filename safely inside the upload directory.

    Only a plain filename is accepted, not an arbitrary path.
    """

    if (
        not isinstance(stored_filename, str)
        or not stored_filename
        or Path(stored_filename).name != stored_filename
        or stored_filename in {".", ".."}
    ):
        raise ValueError("Invalid stored filename.")

    directory = get_upload_directory(upload_dir)

    resolved_path = (directory / stored_filename).resolve()

    if resolved_path.parent != directory:
        raise ValueError("Invalid upload file path.")

    return resolved_path


# ==========================================
# SAVE UPLOADED IMAGE
# ==========================================

def save_uploaded_image(
    image_bytes: bytes,
    upload_dir=None,
):
    """
    Save a validated answer image and generate its thumbnail.

    Filenames are generated by the server.
    The original uploaded filename is never used.
    """

    directory = get_upload_directory(upload_dir)

    image, processed_bytes = _prepare_image(image_bytes)

    unique_id = uuid.uuid4().hex

    stored_filename = f"{unique_id}.jpg"
    thumbnail_filename = f"{unique_id}_thumb.jpg"

    image_path = get_safe_upload_path(
        stored_filename,
        directory,
    )

    thumbnail_path = get_safe_upload_path(
        thumbnail_filename,
        directory,
    )

    thumbnail = image.copy()

    thumbnail.thumbnail(
        THUMBNAIL_SIZE,
        Image.Resampling.LANCZOS,
    )

    thumbnail_buffer = io.BytesIO()

    thumbnail.save(
        thumbnail_buffer,
        format="JPEG",
        quality=80,
        optimize=True,
    )

    # Write temporary files first, then move them into place.
    image_temp_path = directory / f".{unique_id}.tmp"
    thumbnail_temp_path = directory / f".{unique_id}_thumb.tmp"

    try:
        image_temp_path.write_bytes(processed_bytes)

        thumbnail_temp_path.write_bytes(
            thumbnail_buffer.getvalue()
        )

        image_temp_path.replace(image_path)

        thumbnail_temp_path.replace(thumbnail_path)

    except OSError:
        for temporary_path in (
            image_temp_path,
            thumbnail_temp_path,
            image_path,
            thumbnail_path,
        ):
            try:
                temporary_path.unlink(missing_ok=True)
            except OSError:
                pass

        raise

    return {
        "filename": stored_filename,
        "thumbnail_filename": thumbnail_filename,
        "file_path": str(image_path),
        "thumbnail_path": str(thumbnail_path),
        "file_size": len(processed_bytes),
        "content_type": "image/jpeg",
    }


# ==========================================
# READ STORED IMAGE
# ==========================================

def read_uploaded_image(
    stored_filename: str,
    upload_dir=None,
) -> bytes:
    """
    Read an image using its server-generated stored filename.
    """

    image_path = get_safe_upload_path(
        stored_filename,
        upload_dir,
    )

    if not image_path.is_file():
        raise FileNotFoundError("Uploaded image was not found.")

    return image_path.read_bytes()


# ==========================================
# GENERATE THUMBNAIL FROM STORED IMAGE
# ==========================================

def create_image_thumbnail(
    stored_filename: str,
    upload_dir=None,
):
    """
    Generate a thumbnail for an existing stored image.
    """

    image_bytes = read_uploaded_image(
        stored_filename,
        upload_dir,
    )

    image, _ = _prepare_image(image_bytes)

    image.thumbnail(
        THUMBNAIL_SIZE,
        Image.Resampling.LANCZOS,
    )

    thumbnail_filename = (
        f"{Path(stored_filename).stem}_thumb.jpg"
    )

    thumbnail_path = get_safe_upload_path(
        thumbnail_filename,
        upload_dir,
    )

    temporary_path = thumbnail_path.with_name(
        f".{thumbnail_path.stem}.tmp"
    )

    try:
        image.save(
            temporary_path,
            format="JPEG",
            quality=80,
            optimize=True,
        )

        temporary_path.replace(thumbnail_path)

    except OSError:
        try:
            temporary_path.unlink(missing_ok=True)
        except OSError:
            pass

        raise

    return {
        "thumbnail_filename": thumbnail_filename,
        "thumbnail_path": str(thumbnail_path),
    }
